import axios from 'axios';

const BASE_URL = 'http://localhost:8081/storageunit';

// Axios instance for POST and DELETE operations
const axiosClient = axios.create({
  baseURL: BASE_URL,
  headers: {
    'Content-Type': 'application/json',
  },
});

export const storageUnitApi = {
  /**
   * READ: Display All Storage Units using native Fetch API
   * GET /storageunit/displayall
   */
  async getAll() {
    const response = await fetch(`${BASE_URL}/displayall`);
    if (!response.ok) {
      throw new Error(`Failed to fetch records (HTTP ${response.status})`);
    }
    return await response.json();
  },

  /**
   * CREATE: Add new Storage Unit using Axios
   * POST /storageunit/add
   * NOTE: ID is auto-generated by the backend database
   */
  async add(storageUnit) {
    const response = await axiosClient.post('/add', storageUnit);
    return response.data;
  },

  /**
   * DELETE: Delete Storage Unit by ID using Axios
   * DELETE /storageunit/delete/{id}
   */
  async delete(id) {
    const response = await axiosClient.delete(`/delete/${id}`);
    return response.data;
  },
};

export default storageUnitApi;
